func main() {
	// set application config
	var app application
	godotenv.Load()

	// get environment variables
	port := os.Getenv("PORT")
	dbUser := os.Getenv("DB_USER")
	dbPass := os.Getenv("DB_PASSWORD")
	dbName := os.Getenv("DB_NAME")
	dbPort := os.Getenv("DB_PORT")
	dbSslmode := os.Getenv("DB_SSLMODE")
	dbTimezone := os.Getenv("DB_TIMEZONE")
	dbTimeout := os.Getenv("DB_CONNECT_TIMEOUT")
	dbHost := os.Getenv("DB_HOST")

	// read from command line
	flag.StringVar(
		&app.DSN,
		"dsn",
		fmt.Sprintf("host=%s port=%s user=%s password=%s dbname=%s sslmode=%s timezone=%s connect_timeout=%s", dbHost, dbPort, dbUser, dbPass, dbName, dbSslmode, dbTimezone, dbTimeout),
		"Postgres connection string",
	)
	flag.StringVar(
		&app.JWTSecret, "jwt-secret", os.Getenv("JWT_SECRET"), "Signing secret")
	flag.StringVar(
		&app.JWTIssuer, "jwt-issuer", "localhost", "Signing issuer")
	flag.StringVar(
		&app.JWTAudience, "jwt-audience", "localhost", "Signing audience")
	flag.StringVar(
		&app.CookieDomain, "cookie-domain", "localhost", "Cookie domain")
	flag.StringVar(
		&app.Domain, "domain", "localhost", "Domain")
	flag.DurationVar(
		&app.RefreshGrace, "refresh-grace", 10*time.Second,
		"How long a consumed refresh token is still accepted, for concurrent tabs")
	flag.StringVar(
		&app.IGDBClientID, "igdb-client-id", os.Getenv("IGDB_CLIENT_ID"),
		"Twitch application client id, used for IGDB")
	flag.StringVar(
		&app.IGDBClientSecret, "igdb-client-secret", os.Getenv("IGDB_CLIENT_SECRET"),
		"Twitch application client secret, used for IGDB")
	flag.Parse()

	if app.IGDBClientID != "" && app.IGDBClientSecret != "" {
		app.IGDB = igdb.New(igdb.Config{
			ClientID:     app.IGDBClientID,
			ClientSecret: app.IGDBClientSecret,
		})
	} else {
		// Not fatal on purpose: everything except game search still works, so
		// the project runs without a Twitch application of your own.
		log.Println("IGDB credentials not set; game search will answer 503")
	}

	// connect to database
	gormConn, err := app.connectGormDB()
	if err != nil {
		log.Fatal(err)
	}
	app.GormDB = gormConn
	app.DB = &dbrepo.PostgresDBRepo{GormDB: gormConn}

	// if err := app.runSchemaFix(); err != nil {
	// 	log.Fatal(err)
	// }

	db, _ := app.GormDB.DB()
	defer db.Close()

	app.auth = Auth{
		Issuer:             app.JWTIssuer,
		Audience:           app.JWTAudience,
		Secret:             app.JWTSecret,
		TokenExpiry:        time.Minute * 15,
		RefreshTokenExpiry: time.Hour * 24,
		CookiePath:         "/",                    // root path
		CookieName:         "__Host-refresh_token", // secure, httponly, samesite=lax cookie name
		CookieDomain:       "",
	}

	// 20 failures per 15 minutes from one address. Far more than a person who
	// forgot their password produces, low enough to cap how much bcrypt work a
	// single attacker can force.
	app.loginIPLimiter = ratelimit.New(20, 15*time.Minute)

	// 5 failures per minute against one account. The window is short on
	// purpose: anyone who knows a friend's email can hold that account blocked
	// by failing logins, so the block has to expire fast. It still caps a
	// distributed attacker at 300 guesses an hour, which against bcrypt is
	// nothing.
	app.loginEmailLimiter = ratelimit.New(5, time.Minute)

	// 60 a minute per address. A person typing a name produces a handful;
	// this is generous for them and still caps a script.
	app.usernameCheckLimiter = ratelimit.New(60, time.Minute)

	log.Printf("starting tooManyHours API server on %s:%s", app.Domain, port)
	log.Printf("version: %s", apiVersion)

	// start a web server
	err = app.routes().Run(fmt.Sprintf(":%s", port))
	if err != nil {
		log.Fatal(err)
	}
}
