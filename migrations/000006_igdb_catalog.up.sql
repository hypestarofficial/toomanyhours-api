-- A game with no IGDB identity cannot exist under the new rule. With the seven
-- above mapped this deletes nothing; if it ever deletes a row that a list
-- points at, the RESTRICT on user_games.game_id stops the migration loudly,
-- which is the correct outcome.
DELETE FROM public.games WHERE igdb_id IS NULL;

ALTER TABLE public.games ALTER COLUMN igdb_id SET NOT NULL;
ALTER TABLE public.games ADD CONSTRAINT games_igdb_id_key UNIQUE (igdb_id);

-- Superseded by tags. Their 15 seeded rows were test data.
DROP TABLE public.games_genres;
DROP TABLE public.genres;

-- Every games row was inserted with a client-supplied Steam id, so the identity
-- sequence still sits near 1. The first generated id would be 1, and left alone
-- the sequence would eventually walk into 730 - as a duplicate key on a table
-- that had been working for months.
DO $$
DECLARE next_id bigint;
BEGIN
    SELECT coalesce(max(id), 0) + 1 INTO next_id FROM public.games;
    EXECUTE format('ALTER TABLE public.games ALTER COLUMN id RESTART WITH %s', next_id);
END $$;
