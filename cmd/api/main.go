// apiVersion is the API's own version, independent of the frontend's: two
// repositories with two histories.
//
// A constant rather than an env var. It used to be os.Getenv("VERSION") read
// from .env, which is gitignored — so GET / reported an empty string on any
// checkout but this one. A version that only exists on one machine is not a
// version.
const apiVersion = "0.4.0"

type application struct {
	DSN          string
	Domain       string
	GormDB       *gorm.DB
	DB           *dbrepo.PostgresDBRepo
	auth         Auth
	JWTSecret    string
	JWTIssuer    string
	JWTAudience  string
	CookieDomain string
	// Login limiters. Two keys because they defend different attacks: per-IP
	// catches password spraying across many accounts, per-email catches a
	// brute force against one account even from rotating addresses.
	loginIPLimiter    *ratelimit.Limiter
	loginEmailLimiter *ratelimit.Limiter
	// Availability checks are unauthenticated and hit the database on a
	// debounced keystroke. The frontend's debounce is a courtesy this endpoint
	// cannot rely on.
	usernameCheckLimiter *ratelimit.Limiter
	// How long a just-consumed refresh token is still accepted as a concurrent
	// retry rather than a replay. Configurable so tests can drive it to zero.
	RefreshGrace     time.Duration
	IGDBClientID     string
	IGDBClientSecret string
	// nil when credentials are unset. The app still boots and search answers
	// 503, so this project runs for anyone without a Twitch application.
	IGDB *igdb.Client
}

func emailValidator(fl validator.FieldLevel) bool {
	if _, err := mail.ParseAddress(fl.Field().String()); err == nil {
		return true
	}
	return false
}

func init() {
	if v, ok := binding.Validator.Engine().(*validator.Validate); ok {
		v.RegisterValidation("email", emailValidator)
	}
}

