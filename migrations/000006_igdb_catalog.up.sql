-- The catalog becomes IGDB-native.
--
-- games.id stays a surrogate key. Using IGDB's ids as the primary key would be
-- the same bet that Steam's ids were, and this migration is the cost of having
-- lost that bet once.
--
-- Crucially the seven existing rows keep their ids, so user_games needs no
-- changes at all: 14 list entries stay valid with their categories, ratings and
-- reviews. The old Steam numbers survive as meaningless surrogates.

-- One table for the three lists IGDB attaches to a game. Three tables would
-- mean writing the same import, join and query three times, forever.
CREATE TABLE public.tags (
    id         integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    -- Which list this belongs to. Called facet, not kind, because games.kind
    -- below means something entirely different.
    facet      text NOT NULL,
    igdb_id    integer NOT NULL,
    name       text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT tags_pkey PRIMARY KEY (id),
    CONSTRAINT tags_facet_check CHECK (facet IN ('genre', 'theme', 'game_mode')),
    -- What makes import idempotent without a pre-flight check.
    CONSTRAINT tags_facet_igdb_id_key UNIQUE (facet, igdb_id)
);

CREATE TABLE public.games_tags (
    game_id integer NOT NULL,
    tag_id  integer NOT NULL,

    CONSTRAINT games_tags_pkey PRIMARY KEY (game_id, tag_id),
    -- CASCADE both ways, unlike user_games.game_id: a lost tag link destroys
    -- nothing a person wrote.
    CONSTRAINT games_tags_game_id_fkey FOREIGN KEY (game_id)
        REFERENCES public.games(id) ON DELETE CASCADE,
    CONSTRAINT games_tags_tag_id_fkey FOREIGN KEY (tag_id)
        REFERENCES public.tags(id) ON DELETE CASCADE
);

CREATE INDEX games_tags_tag_id_idx ON public.games_tags (tag_id);

ALTER TABLE public.games ADD COLUMN igdb_id integer;
-- Default so the column can be NOT NULL immediately; every real row gets a
-- value from IGDB on import.
ALTER TABLE public.games ADD COLUMN kind text NOT NULL DEFAULT 'unknown';

